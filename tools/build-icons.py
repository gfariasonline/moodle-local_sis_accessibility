#!/usr/bin/env python3
"""Compile the locally licensed Sienna, Material and Lucide SVG assets."""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
root=Path(__file__).resolve().parent.parent

def readsvg(path):
    svg=ET.fromstring(path.read_text())
    allowed={'fill','stroke','stroke-width','stroke-linecap','stroke-linejoin'}
    return {'viewBox':svg.attrib.get('viewBox','0 0 24 24'),'attrs':{k:v for k,v in svg.attrib.items() if k in allowed},
            'nodes':[{'tag':n.tag.split('}')[-1], 'attrs':dict(n.attrib)} for n in svg if isinstance(n.tag,str) and n.tag.split('}')[-1] in ['path','circle','line','rect','polyline','polygon','ellipse']]}

names={'font-weight':'formatBoldIcon','line-height':'lineHeightIcon','letter-spacing':'letterSpacingIcon',
       'readable-font':'dyslexiaFontIcon','highlight-links':'highlightLinksIcon','highlight-title':'highlightTitleIcon',
       'monochrome':'monochromeIcon','low-saturation':'lowSaturationIcon','high-saturation':'highSaturationIcon',
       'high-contrast':'highContrastIcon','light-contrast':'lightContrastIcon','dark-contrast':'darkContrastIcon',
       'big-cursor':'bigCursorIcon','readable-guide':'readingGuideIcon','stop-animations':'stopAnimationsIcon',
       'reset':'reset','close':'close','font-size':'font-size'}
icons={k:readsvg(root/'thirdparty/sienna/icons'/(v+'.svg')) for k,v in names.items()}
icons['launcher']=readsvg(root/'thirdparty/icons/material/launcher.svg')
new={'seizure-safe':'zap-off','visually-impaired':'eye','adhd-friendly':'info',
     'cognitive-learning':'book-open','hide-images':'image-off','image-tooltips':'message-square'}
icons.update({k:readsvg(root/'thirdparty/icons/lucide'/(v+'.svg')) for k,v in new.items()})
def js_literal(value):
    """Keep generated SVG data readable and compatible with Moodle's line limit."""
    lines = json.dumps(value, indent=4).splitlines()
    output = []
    for line in lines:
        if len(line) <= 120:
            output.append(line)
            continue
        prefix, encoded = line.split(': ', 1)
        comma = ',' if encoded.endswith(',') else ''
        text = json.loads(encoded.rstrip(','))
        chunks = [json.dumps(text[i:i + 80]) for i in range(0, len(text), 80)]
        output.append(prefix + ': ' + chunks[0] + ' +')
        for chunk in chunks[1:-1]:
            output.append(' ' * (len(prefix) - len(prefix.lstrip()) + 4) + chunk + ' +')
        output.append(' ' * (len(prefix) - len(prefix.lstrip()) + 4) + chunks[-1] + comma)
    return '\n'.join(output)

output='''// Generated by tools/build-icons.py from locally licensed SVG files.
// Sienna MIT, Material Apache2.0, Lucide ISC/Feather MIT. See thirdparty licenses.
/** @module local_sis_accessibility/icons */
const icons = '''+js_literal(icons)+''';
export const createIcon = (doc, key) => {
    const data = icons[key] || icons.launcher;
    const svg = doc.createElementNS('http://www.w3.org/2000/svg', 'svg');
    svg.setAttribute('viewBox', data.viewBox);
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');
    Object.entries(data.attrs).forEach(([key, value]) => svg.setAttribute(key, value));
    data.nodes.forEach(node => {
        const child = doc.createElementNS(svg.namespaceURI, node.tag);
        Object.entries(node.attrs).forEach(([key, value]) => child.setAttribute(key, value));
        svg.append(child);
    });
    return svg;
};
'''
(root/'amd/src/icons.js').write_text(output)
